def b_oil_litres_from_level_cm(raw_value: Any) -> str:
    try:
        level_m = Decimal(str(raw_value).strip()) / 100
    except (InvalidOperation, ValueError) as exc:
        raise ValueError("B楼油罐液位缺失或不是有效数字（厘米）") from exc
    if not level_m.is_finite() or not Decimal(0) <= level_m <= Decimal("2.2"):
        raise ValueError("B楼油罐液位超出标定范围0～220厘米")
    if level_m == 0:
        return "0"
    # Decimal keeps exact midpoint ties on the lower calibration row.
    index = max(1, int((level_m / Decimal("0.011")).to_integral_value(rounding=ROUND_HALF_DOWN)))
    return str(_B_TANK_LITRES[index - 1])
